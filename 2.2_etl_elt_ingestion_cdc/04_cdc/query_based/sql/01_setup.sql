CREATE SCHEMA IF NOT EXISTS query_source;
CREATE SCHEMA IF NOT EXISTS query_target;

CREATE TABLE IF NOT EXISTS query_source.customer_changes (
    change_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_key text NOT NULL UNIQUE,
    changed_at timestamptz NOT NULL,
    customer_id text NOT NULL,
    operation text NOT NULL CHECK (operation IN ('upsert', 'hard_delete')),
    customer_name text,
    region text,
    is_deleted boolean NOT NULL DEFAULT false,
    CHECK (
        (operation = 'upsert' AND customer_name IS NOT NULL AND region IS NOT NULL)
        OR operation = 'hard_delete'
    )
);

CREATE TABLE IF NOT EXISTS query_target.customers (
    customer_id text PRIMARY KEY,
    source_change_id bigint NOT NULL,
    customer_name text NOT NULL,
    region text NOT NULL,
    is_deleted boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS query_target.checkpoint (
    checkpoint_id integer PRIMARY KEY CHECK (checkpoint_id = 1),
    last_changed_at timestamptz NOT NULL,
    last_change_id bigint NOT NULL
);

