CREATE SCHEMA IF NOT EXISTS source;
CREATE SCHEMA IF NOT EXISTS target;

CREATE TABLE IF NOT EXISTS source.sales_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key text NOT NULL UNIQUE,
    sale_id text NOT NULL,
    updated_at timestamptz NOT NULL,
    status text NOT NULL,
    amount numeric(12, 2) NOT NULL CHECK (amount >= 0),
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS target.sales_by_timestamp (
    sale_id text PRIMARY KEY,
    source_event_id bigint NOT NULL,
    status text NOT NULL,
    amount numeric(12, 2) NOT NULL,
    is_deleted boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS target.sales_by_id (
    sale_id text PRIMARY KEY,
    source_event_id bigint NOT NULL,
    status text NOT NULL,
    amount numeric(12, 2) NOT NULL,
    is_deleted boolean NOT NULL
);

CREATE TABLE IF NOT EXISTS target.load_checkpoint (
    pipeline_name text PRIMARY KEY,
    last_event_id bigint NOT NULL DEFAULT 0,
    last_updated_at timestamptz NOT NULL DEFAULT TIMESTAMPTZ '1970-01-01 00:00:00+00',
    last_updated_event_id bigint NOT NULL DEFAULT 0
);

