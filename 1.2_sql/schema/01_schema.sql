CREATE TABLE IF NOT EXISTS departments (
    department_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS employees (
    employee_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id integer NOT NULL REFERENCES departments (department_id),
    manager_id integer REFERENCES employees (employee_id),
    first_name text NOT NULL,
    last_name text NOT NULL,
    email text NOT NULL UNIQUE,
    hired_at date NOT NULL,
    salary numeric(12, 2) NOT NULL CHECK (salary > 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name text NOT NULL,
    last_name text NOT NULL,
    email text NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS products (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name text NOT NULL UNIQUE,
    category text NOT NULL,
    list_price numeric(10, 2) NOT NULL CHECK (list_price >= 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (customer_id),
    employee_id integer NOT NULL REFERENCES employees (employee_id),
    order_date timestamptz NOT NULL,
    status text NOT NULL CHECK (
        status IN ('new', 'processing', 'shipped', 'completed', 'cancelled')
    ),
    shipped_at timestamptz,
    CHECK (shipped_at IS NULL OR shipped_at >= order_date)
);

CREATE TABLE IF NOT EXISTS order_items (
    order_id bigint NOT NULL REFERENCES orders (order_id),
    line_number smallint NOT NULL CHECK (line_number > 0),
    product_id integer NOT NULL REFERENCES products (product_id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, line_number)
);

CREATE OR REPLACE VIEW monthly_revenue AS
SELECT
    date_trunc('month', o.order_date AT TIME ZONE 'UTC') AS revenue_month,
    count(DISTINCT o.order_id) AS order_count,
    sum(oi.quantity * oi.unit_price)::numeric(14, 2) AS revenue
FROM orders AS o
JOIN order_items AS oi ON oi.order_id = o.order_id
WHERE o.status IN ('shipped', 'completed')
GROUP BY date_trunc('month', o.order_date AT TIME ZONE 'UTC');
