CREATE TABLE IF NOT EXISTS dim_date (
    date_key integer PRIMARY KEY,
    calendar_date date NOT NULL UNIQUE,
    day_of_month smallint NOT NULL CHECK (day_of_month BETWEEN 1 AND 31),
    day_of_week smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    month_number smallint NOT NULL CHECK (month_number BETWEEN 1 AND 12),
    month_name text NOT NULL,
    quarter_number smallint NOT NULL CHECK (quarter_number BETWEEN 1 AND 4),
    year_number smallint NOT NULL,
    is_weekend boolean NOT NULL,
    CHECK (date_key = to_char(calendar_date, 'YYYYMMDD')::integer)
);

CREATE TABLE IF NOT EXISTS dim_customer (
    customer_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id text NOT NULL,
    first_name text NOT NULL,
    last_name text NOT NULL,
    address_line text NOT NULL,
    city text NOT NULL,
    region text NOT NULL,
    valid_from date NOT NULL,
    valid_to date NOT NULL DEFAULT DATE '9999-12-31',
    is_current boolean NOT NULL DEFAULT true,
    CHECK (valid_from < valid_to),
    CHECK (is_current = (valid_to = DATE '9999-12-31'))
);

CREATE UNIQUE INDEX IF NOT EXISTS dim_customer_one_current_version
    ON dim_customer (customer_id)
    WHERE is_current;

CREATE INDEX IF NOT EXISTS dim_customer_as_of_lookup
    ON dim_customer (customer_id, valid_from, valid_to);

CREATE TABLE IF NOT EXISTS dim_product (
    product_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id text NOT NULL UNIQUE,
    product_name text NOT NULL,
    category text NOT NULL
);

CREATE TABLE IF NOT EXISTS fact_sales (
    sales_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_order_id text NOT NULL,
    source_line_number smallint NOT NULL CHECK (source_line_number > 0),
    date_key integer NOT NULL REFERENCES dim_date (date_key),
    customer_sk bigint NOT NULL REFERENCES dim_customer (customer_sk),
    product_sk bigint NOT NULL REFERENCES dim_product (product_sk),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
    sales_amount numeric(14, 2)
        GENERATED ALWAYS AS ((quantity * unit_price)::numeric(14, 2)) STORED,
    UNIQUE (source_order_id, source_line_number)
);

CREATE INDEX IF NOT EXISTS fact_sales_date_customer_product
    ON fact_sales (date_key, customer_sk, product_sk);
